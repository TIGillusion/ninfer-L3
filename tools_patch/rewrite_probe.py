import re, sys

f = "src/targets/qwen3_6/impl/runtime/request_plan_impl.h"
data = open(f, "rb").read()

nl = b"\r\n" if data.count(b"\r\n") > data.count(b"\n") else b"\n"
print("newline:", nl)

start_re = re.compile(
    rb"    std::optional<std::uint32_t> best_E;\s*\n"
    rb"    for \(const std::uint32_t E : disk_kv->live_state_frontiers\(\)\) \{",
    re.S)
m = start_re.search(data)
assert m, "loop head not found"
i = m.start()

# tail: from the best_E assignment line through the closing brace of the for + return
tail_re = re.compile(
    rb"        if \(!best_E \|\| E > \*best_E\) \{ best_E = E; \}\s*\n"
    rb"    \}\s*\n"
    rb"    return best_E;\s*\n"
    rb"\}", re.S)
m2 = tail_re.search(data, i)
assert m2, "loop tail not found"
j = m2.end()

L = nl

new_body = L.join([
b'    // Candidate frontiers on THIS prompt\'s digest chain whose state gate',
b'    // passes, ascending. (live_state_frontiers is ascending; stable filter.)',
b'    struct GateCandidate {',
b'        std::uint32_t E;',
b'        std::uint32_t full_pages;     // whole main pages required',
b'        bool main_tail_needed;        // E not page aligned: partial tail page',
b'        std::uint32_t bfull_pages;    // MTP backend whole pages',
b'        std::uint32_t bF;             // MTP backend frontier',
b'        bool backend_tail_needed;',
b'    };',
b'    std::vector<GateCandidate> gated;',
b'    std::uint32_t max_full_pages = 0;',
b'    std::uint32_t max_bfull_pages = 0;',
b'    for (const std::uint32_t E : disk_kv->live_state_frontiers()) {',
b'        if (E == 0) { continue; }',
b'        if (E > prompt_tokens) {',
b'            if (trace) {',
b'                disk_kv_logf(\'D\', "l3-probe", "skip | E=%u > prompt=%u", E, prompt_tokens);',
b'            }',
b'            continue;',
b'        }',
b'        // Cheap gate BEFORE the per-page chain walk: every passing candidate',
b'        // requires the state image at E (tail or aligned branch below).',
b'        {',
b'            const auto digest = digests.at(E);',
b'            const DiskKVIdentity gate{.lo      = digest[0],',
b'                                      .hi      = digest[1],',
b'                                      .tag     = tag,',
b'                                      .frontier = E};',
b'            if (!disk_kv->contains(gate, DiskKVKind::StateImage)) {',
b'                if (trace) {',
b'                    disk_kv_logf(\'D\', "l3-probe",',
b'                                 "skip | E=%u state=0 (gate) key=%016llx%016llx tag=%u", E,',
b'                                 (unsigned long long)digest[0], (unsigned long long)digest[1], tag);',
b'                }',
b'                continue;',
b'            }',
b'        }',
b'        const std::uint32_t full_pages = E / static_cast<std::uint32_t>(kPagedKVPageSize);',
b'        if (full_pages == 0) {',
b'            if (trace) {',
b'                disk_kv_logf(\'D\', "l3-probe", "skip | E=%u sub-page", E);',
b'            }',
b'            continue;',
b'        }',
b'        const bool main_tail_needed = (E % static_cast<std::uint32_t>(kPagedKVPageSize)) != 0;',
b'        std::uint32_t bfull_pages = 0;',
b'        std::uint32_t bF = 0;',
b'        bool backend_tail_needed = false;',
b'        if (speculative_backend == SpeculativeBackend::Mtp) {',
b'            bF = backend_frontier_at(speculative_backend, E);',
b'            bfull_pages = bF / static_cast<std::uint32_t>(kPagedKVPageSize);',
b'            backend_tail_needed = (bF % static_cast<std::uint32_t>(kPagedKVPageSize)) != 0;',
b'            if (bfull_pages > max_bfull_pages) { max_bfull_pages = bfull_pages; }',
b'        }',
b'        gated.push_back(GateCandidate{E, full_pages, main_tail_needed,',
b'                                      bfull_pages, bF, backend_tail_needed});',
b'        if (full_pages > max_full_pages) { max_full_pages = full_pages; }',
b'    }',
b'    if (gated.empty()) {',
b'        if (trace) { disk_kv_logf(\'D\', "l3-probe", "no candidate passed"); }',
b'        return std::nullopt;',
b'    }',
b'    // live_state_frontiers is not guaranteed ascending across sessions - sort.',
b'    std::sort(gated.begin(), gated.end(),',
b'              [](const GateCandidate& a, const GateCandidate& b) { return a.E < b.E; });',
b'',
b'    // Single ascending lockstep pass over the shared digest chain: page p is',
b'    // keyed digest((p+1)*64) for BOTH the main and the MTP backend family,',
b'    // so one walk covers both. Run counters track the contiguous-present',
b'    // prefix; a candidate is viable the moment its whole requirement',
b'    // (full_pages [+ tail] [+ backend pages [+ backend tail]]) is inside the',
b'    // run. The old per-candidate full-chain walks were quadratic in chain',
b'    // depth (each deeper seam state re-walked pages 0..E/64 that shallower',
b'    // candidates had just verified): with seam states landing every round a',
b'    // 149K chain paid tens of thousands of mutexed hash lookups per probe -',
b'    // the boundary CPU storm and the waiter_create wedges.',
b'    std::optional<std::uint32_t> best_E;',
b'    std::size_t ci = 0;',
b'    std::uint32_t main_run = 0;',
b'    std::uint32_t backend_run = 0;',
b'    const bool mtp = speculative_backend == SpeculativeBackend::Mtp;',
b'    for (std::uint32_t p = 0; p < max_full_pages; ++p) {',
b'        const auto digest = digests.at((p + 1) * static_cast<std::uint32_t>(kPagedKVPageSize));',
b'        const DiskKVIdentity main_id{.lo       = digest[0],',
b'                                     .hi       = digest[1],',
b'                                     .tag      = tag,',
b'                                     .frontier = (p + 1) *',
b'                                                 static_cast<std::uint32_t>(kPagedKVPageSize)};',
b'        const bool main_ok = disk_kv->contains(main_id, DiskKVKind::MainKV);',
b'        bool backend_ok = false;',
b'        if (mtp) {',
b'            const DiskKVIdentity backend_id{.lo       = digest[0],',
b'                                            .hi       = digest[1],',
b'                                            .tag      = tag,',
b'                                            .frontier = (p + 1) *',
b'                                                        static_cast<std::uint32_t>(kPagedKVPageSize)};',
b'            backend_ok = disk_kv->contains(backend_id, DiskKVKind::BackendKV);',
b'        }',
b'        if (main_ok) { ++main_run; }',
b'        if (mtp && backend_ok) { ++backend_run; }',
b'        if (!main_ok && !mtp) {',
b'            // Prefix broken without an MTP dependency: every remaining',
b'            // candidate is deeper than the run - none can pass.',
b'            break;',
b'        }',
b'        while (ci < gated.size() && gated[ci].full_pages == p + 1) {',
b'            const auto& cand = gated[ci];',
b'            bool viable = main_run >= cand.full_pages &&',
b'                          (!cand.main_tail_needed ||',
b'                           [&] {',
b'                               const auto digest = digests.at(cand.E);',
b'                               const DiskKVIdentity id{.lo       = digest[0],',
b'                                                       .hi       = digest[1],',
b'                                                       .tag      = tag,',
b'                                                       .frontier = cand.E};',
b'                               return disk_kv->contains(id, DiskKVKind::MainKV);',
b'                           }());',
b'            if (viable && mtp) {',
b'                viable = backend_run >= cand.bfull_pages &&',
b'                         (!cand.backend_tail_needed ||',
b'                          [&] {',
b'                              const auto digest = digests.at(cand.bF);',
b'                              const DiskKVIdentity id{.lo       = digest[0],',
b'                                                      .hi       = digest[1],',
b'                                                      .tag      = tag,',
b'                                                      .frontier = cand.bF};',
b'                              return disk_kv->contains(id, DiskKVKind::BackendKV);',
b'                          }());',
b'            }',
b'            if (viable && (!best_E || cand.E > *best_E)) {',
b'                best_E = cand.E;',
b'                if (trace && cand.main_tail_needed) {',
b'                    const auto digest = digests.at(cand.E);',
b'                    disk_kv_logf(\'D\', "l3-probe",',
b'                            "P1@%u | lo=%016llx hi=%016llx tag=%u", cand.E,',
b'                            (unsigned long long)digest[0], (unsigned long long)digest[1], tag);',
b'                }',
b'            }',
b'            ++ci;',
b'        }',
b'        if (ci >= gated.size()) { break; }   // all candidates decided',
b'    }',
b'    return best_E;',
b'}',
])

data = data[:i] + new_body + data[j:]
open(f, "wb").write(data)
print("rewritten ok, newline was", nl)
